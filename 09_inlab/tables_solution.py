"""Write the PS reference tables and long-run transcripts from long-run ChampSim logs.

Run by `./solution-make tables`, which first produces the logs (20M + 25M, policy at the L2C).
Usage: python3 tables_solution.py <dir with <policy>.<trace>.log files>
Writes 09i_results_table.tex (\\tasktwotable, \\taskthreetable), labexam/labexam_table.tex
(\\labexamtable) and task2/long_run.tex, task3/long_run.tex, labexam/long_run.tex (soplex transcripts).
"""
import os, re, sys

LOGS = sys.argv[1]
LAB = os.path.dirname(os.path.abspath(__file__))
TRACES = ["soplex", "bwaves", "mcf", "gcc"]
WARMUP, SIM = 20_000_000, 25_000_000
HEAD = "% Generated by tables_solution.py (./solution-make tables). Do not edit by hand.\n"


def log(policy, trace):
    return open(os.path.join(LOGS, f"{policy}.{trace}.log")).read()


def stats(policy, trace):
    text = log(policy, trace)
    ipc = re.search(r"^CPU 0 cumulative IPC: (\S+)", text, re.M).group(1)
    miss = int(re.search(r"^cpu0_L2C TOTAL .*MISS:\s+(\d+)", text, re.M).group(1))
    lat = float(re.search(r"^cpu0_L1D AVERAGE MISS LATENCY: (\S+)", text, re.M).group(1))
    return ipc, f"{miss / (SIM / 1000):.4f}", f"{lat:.1f}"


def table(macro, policies):
    rows = []
    for t in TRACES:
        for k, p in enumerate(policies):
            ipc, mpki, lat = stats(p, t)
            name = f"\\texttt{{{t}}}" if k == 0 else ""
            rows.append(f"    {name} & \\texttt{{{p.replace('_', chr(92) + '_')}}} & {ipc} & {mpki} & {lat} \\\\")
        rows.append("    \\hline")
    return (f"\\newcommand{{\\{macro}}}{{%\n\\begin{{center}}\n\\begin{{tabular}}{{l|l|r|r|r}}\n"
            "    trace & L2C policy & IPC & L2C MPKI & L1D miss latency (cycles) \\\\\n    \\hline\n"
            + "\n".join(rows[:-1]) + "\n\\end{tabular}\n\\end{center}\n}\n")


def run(target, policy, trace="soplex"):
    """What `make <target> long=1` prints, rebuilt from the log."""
    text = log(policy, trace)
    keep = [l for l in text.splitlines()
            if re.match(r"^(CPU 0 cumulative IPC|cpu0_L2C (TOTAL|LOAD|RFO|WRITEBACK) )", l)]
    miss = int(re.search(r"^cpu0_L2C TOTAL .*MISS:\s+(\d+)", text, re.M).group(1))
    trace_file = re.search(r"^CPU 0 runs (\S+)", text, re.M).group(1)
    trace_file = "/opt/CS231_Traces/" + os.path.basename(trace_file)
    return (f"$ make {target} long=1\nBuilding Champsim/bin/{policy} (L2C replacement = {policy})\n"
            f"Champsim/bin/{policy} --warmup_instructions {WARMUP} \\\n"
            f"    --simulation_instructions {SIM} \\\n    {trace_file}\n" + "\n".join(keep) + f"\ncpu0_L2C MPKI: {miss / (SIM / 1000):.4f}\n")


def transcript(path, *runs):
    with open(os.path.join(LAB, path), "w") as f:
        f.write(HEAD + "\\begin{center}\n\\begin{terminal}\n\\begin{verbatim}\n" + "\n".join(runs)
                + "\\end{verbatim}\n\\end{terminal}\n\\end{center}\n")


with open(os.path.join(LAB, "09i_results_table.tex"), "w") as f:
    f.write(HEAD + table("tasktwotable", ["lru", "mylru"]) + "\n" + table("taskthreetable", ["lru", "ip_based"]))
with open(os.path.join(LAB, "labexam", "labexam_table.tex"), "w") as f:
    f.write(HEAD + table("labexamtable", ["lru", "flip"]))
transcript("task2/long_run.tex", run("lru", "lru"), run("task2", "mylru"))
transcript("task3/long_run.tex", run("task3", "ip_based"))
transcript("labexam/long_run.tex", run("labexam", "flip"))
print("wrote the tables and the long-run transcripts")
