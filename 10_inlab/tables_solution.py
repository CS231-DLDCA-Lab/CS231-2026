"""Write the PS reference tables and long-run transcripts from long-run ChampSim logs.

Run by `./solution-make tables`, which first produces the logs (20M + 25M).
Usage: python3 tables_solution.py <dir with <binary>.<trace>.log files>
Binaries: lru, mylru, ip_based (policies at the L2C) and exclusive (task3's ChampSim, lru everywhere).
Writes 10i_results_table.tex (\\taskonetable, \\tasktwotable, \\taskthreetable) and
task1/long_run.tex, task2/long_run.tex, task3/long_run.tex (soplex transcripts).
The lab exam's files (labexam/labexam_table.tex, labexam/long_run.tex) are fixed and not written here.
"""
import os, re, sys

LOGS = sys.argv[1]
LAB = os.path.dirname(os.path.abspath(__file__))
TRACES = ["soplex", "bwaves", "mcf", "gcc"]
WARMUP, SIM = 20_000_000, 25_000_000
HEAD = "% Generated by tables_solution.py (./solution-make tables). Do not edit by hand.\n"
STATS = r"^(CPU 0 cumulative IPC|cpu0_L2C (TOTAL|LOAD|RFO|WRITEBACK) |LLC (TOTAL|LOAD|RFO|WRITEBACK) |L2C LINES ALSO IN LLC)"


def log(binary, trace):
    return open(os.path.join(LOGS, f"{binary}.{trace}.log")).read()


def misses(text, cache):
    return int(re.search(rf"^{cache} TOTAL .*MISS:\s+(\d+)", text, re.M).group(1))


def stats(binary, trace):
    text = log(binary, trace)
    ipc = re.search(r"^CPU 0 cumulative IPC: (\S+)", text, re.M).group(1)
    lat = float(re.search(r"^cpu0_L1D AVERAGE MISS LATENCY: (\S+)", text, re.M).group(1))
    return (ipc, f"{misses(text, 'cpu0_L2C') / (SIM / 1000):.4f}", f"{misses(text, 'LLC') / (SIM / 1000):.4f}",
            f"{lat:.1f}")


def table(macro, rows_of, head):
    """rows_of: [(binary, label)] per trace, first row is the baseline."""
    rows = []
    for t in TRACES:
        for k, (b, label) in enumerate(rows_of):
            ipc, l2, llc, lat = stats(b, t)
            name = f"\\texttt{{{t}}}" if k == 0 else ""
            rows.append(f"    {name} & {label} & {ipc} & {l2} & {llc} & {lat} \\\\")
        rows.append("    \\hline")
    return (f"\\newcommand{{\\{macro}}}{{%\n\\begin{{center}}\n\\begin{{tabular}}{{l|l|r|r|r|r}}\n"
            f"    trace & {head} & IPC & L2C MPKI & LLC MPKI & L1D miss latency \\\\\n    \\hline\n"
            + "\n".join(rows[:-1]) + "\n\\end{tabular}\n\\end{center}\n}\n")


def run(target, binary, build, path, trace="soplex"):
    """What `make <target> long=1` prints, rebuilt from the log."""
    text = log(binary, trace)
    keep = [l for l in text.splitlines() if re.match(STATS, l)]
    trace_file = "/opt/CS231_Traces/" + os.path.basename(re.search(r"^CPU 0 runs (\S+)", text, re.M).group(1))
    return (f"$ make {target} long=1\n{build}\n{path} --warmup_instructions {WARMUP} \\\n"
            f"    --simulation_instructions {SIM} \\\n    {trace_file}\n" + "\n".join(keep)
            + f"\ncpu0_L2C MPKI: {misses(text, 'cpu0_L2C') / (SIM / 1000):.4f}"
            + f"\nLLC MPKI: {misses(text, 'LLC') / (SIM / 1000):.4f}\n")


def policy_run(target, policy):
    return run(target, policy, f"Building Champsim/bin/{policy} (L2C replacement = {policy})", f"Champsim/bin/{policy}")


def transcript(path, *runs):
    with open(os.path.join(LAB, path), "w") as f:
        f.write(HEAD + "\\begin{center}\n\\begin{terminal}\n\\begin{verbatim}\n" + "\n".join(runs)
                + "\\end{verbatim}\n\\end{terminal}\n\\end{center}\n")


LRU = ("lru", "\\texttt{lru}")
with open(os.path.join(LAB, "10i_results_table.tex"), "w") as f:
    f.write(HEAD + table("taskonetable", [LRU, ("mylru", "\\texttt{mylru}")], "L2C policy") + "\n"
            + table("tasktwotable", [LRU, ("ip_based", "\\texttt{ip\\_based}")], "L2C policy") + "\n"
            + table("taskthreetable", [("lru", "given (NINE)"), ("exclusive", "exclusive LLC")], "cache.cc"))
transcript("task1/long_run.tex", policy_run("lru", "lru"), policy_run("task1", "mylru"))
transcript("task2/long_run.tex", policy_run("task2", "ip_based"))
transcript("task3/long_run.tex", run("task3", "exclusive",
                                     "Building .task3_champsim/bin/champsim with task3.patch and task3/cache.cc",
                                     ".task3_champsim/bin/champsim"))
print("wrote the tables and the long-run transcripts")
