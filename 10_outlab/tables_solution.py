"""Write the PS reference tables from long-run ChampSim logs.

Run by `./solution-make tables`, which first produces the logs (20M + 25M).
Usage: python3 tables_solution.py <dir with <binary>.<trace>.log files>
Binaries: lru (given ChampSim, lru at the LLC) and task1..task4 (solutions).
Writes taskN/results_table.tex and taskN/expected_output_long.txt (the longcheck reference) for N = 1..4.
"""
import os, re, sys

LOGS = sys.argv[1]
LAB = os.path.dirname(os.path.abspath(__file__))
TRACES = ["soplex", "bwaves", "mcf", "gcc"]
SIM = 25_000_000
HEAD = "% Generated by tables_solution.py (./solution-make tables). Do not edit by hand.\n"


def stats(binary, trace):
    text = open(os.path.join(LOGS, f"{binary}.{trace}.log")).read()
    get = lambda pat: re.search(pat, text, re.M).group(1)
    demand = int(get(r"^LLC LOAD .*MISS:\s+(\d+)")) + int(get(r"^LLC RFO .*MISS:\s+(\d+)"))
    return {"ipc": get(r"^CPU 0 cumulative IPC: (\S+)"), "mpki": f"{demand / (SIM / 1000):.4f}",
            "doa": get(r"^LLC DEAD ON ARRIVAL: (\S+)%"), "pred": get(r"^LLC PREDICTED DEAD: (\S+)%")}


def write(task, cols, rows):
    """cols: header cells after `trace`; rows: function trace -> list of cells."""
    body = "\n".join(f"    \\texttt{{{t}}} & " + " & ".join(rows(t)) + " \\\\" for t in TRACES)
    with open(os.path.join(LAB, task, "results_table.tex"), "w") as f:
        f.write(HEAD + f"\\begin{{center}}\n\\begin{{tabular}}{{l|{'r' * len(cols)}}}\n"
                f"    trace & {' & '.join(cols)} \\\\\n    \\hline\n{body}\n\\end{{tabular}}\n\\end{{center}}\n")


def compare(task, base, base_name, new, new_name):
    write(task, [f"IPC ({base_name})", f"LLC MPKI ({base_name})", f"IPC ({new_name})", f"LLC MPKI ({new_name})"],
          lambda t: [stats(base, t)["ipc"], stats(base, t)["mpki"], stats(new, t)["ipc"], stats(new, t)["mpki"]])


compare("task1", "lru", "LRU", "task1", "SRRIP")
write("task2", ["dead on arrival (\\%)", "predicted dead (\\%)"],
      lambda t: [stats("task2", t)["doa"], stats("task2", t)["pred"]])
compare("task3", "task1", "Task 1", "task3", "Task 3")
compare("task4", "task3", "Task 3", "task4", "Task 4")

# longcheck references, in the format of the makefile's `results`: trace IPC LLC-MPKI DOA% PRED%
for task in ["task1", "task2", "task3", "task4"]:
    with open(os.path.join(LAB, task, "expected_output_long.txt"), "w") as f:
        for t in TRACES:
            r = stats(task, t)
            f.write(f"{t} {r['ipc']} {r['mpki']} {r['doa']}% {r['pred']}%\n")
